import {chromium} from 'playwright';
import {mkdir, writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('.qa/results',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
try{
  await page.goto('http://127.0.0.1:8080',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.querySelector('#idea-canvas').width>0);
  assert.equal(await page.locator('h1').count(),1);
  assert.equal(await page.getByText('Wunderwerk Worlds',{exact:true}).count(),0);
  assert.equal(await page.locator('.card-meta').first().innerText(),'Seit 2026 · laufend');
  assert.match(await page.locator('.hero-description').innerText(),/Masterstudent der Pharmazeutischen Biotechnologie/);
  checks.push('Master seit 2026 enthalten; entferntes Projekt fehlt.');
  await page.screenshot({path:'.qa/results/desktop.webp',type:'webp',quality:72});
  await page.getByRole('button',{name:'Prüfen',exact:true}).click();
  assert.equal(await page.locator('.hero-experience').getAttribute('data-scene'),'pruefen');
  assert.equal(await page.getByRole('button',{name:'Prüfen',exact:true}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Animationen pausieren',exact:true}).first().click();
  const frame1=await page.locator('canvas').evaluate(el=>el.toDataURL());
  await page.waitForTimeout(250);
  const frame2=await page.locator('canvas').evaluate(el=>el.toDataURL());
  assert.equal(frame1,frame2,'Pause must stop canvas rendering.');
  await page.getByRole('button',{name:'Animationen abspielen',exact:true}).first().click();
  checks.push('Startszene: Auswahl und tatsächliche Animationspause funktionieren.');
  const summary=page.locator('[data-dialog="study"] summary');
  await summary.click();
  assert.equal(await page.locator('dialog[open]').count(),1);
  assert.match(await page.locator('#dialog-title').innerText(),/Wissenschaft/);
  await page.screenshot({path:'.qa/results/dialog.webp',type:'webp',quality:72});
  for(let i=0;i<5;i++)await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.querySelector('dialog').contains(document.activeElement)),true);
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!document.querySelector('dialog').open);
  assert.equal(await summary.evaluate(el=>document.activeElement===el),true);
  assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('dialog-open')),false);
  checks.push('Dialog: Inhalt, Fokusbegrenzung, Escape und Fokusrückgabe funktionieren.');
  await page.locator('.route-play').click();
  assert.equal(await page.locator('.project-demo').evaluate(el=>el.classList.contains('is-playing')),true);
  await page.waitForTimeout(150);
  const offset=await page.locator('.route-line').evaluate(el=>parseFloat(getComputedStyle(el).strokeDashoffset));
  assert.ok(offset>0 && offset<100,'Route animation must progress.');
  checks.push('Routendemo wird interaktiv abgespielt.');
  for(const width of [320,390,520,768,1280]){
    await page.setViewportSize({width,height:900});
    await page.goto('http://127.0.0.1:8080',{waitUntil:'networkidle'});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`Horizontal overflow at ${width}px`);
    await page.locator('#kontakt').scrollIntoViewIfNeeded();
    await page.waitForTimeout(850);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`Contact overflow at ${width}px`);
    checks.push(`Kein horizontaler Überlauf bei ${width}px.`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:8080',{waitUntil:'networkidle'});
  await page.screenshot({path:'.qa/results/mobile.webp',type:'webp',quality:72});
  await page.getByRole('button',{name:'Menü'}).click();
  assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
  await page.locator('#navigation').getByRole('link',{name:'Mein Weg'}).click();
  assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'false');
  await page.locator('[data-dialog="quality"] summary').click();
  assert.equal(await page.locator('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'Mobile dialog overflow.');
  await page.getByRole('button',{name:'Detailfenster schließen'}).click();
  await page.waitForFunction(()=>!document.querySelector('dialog').open);
  checks.push('Mobiles Menü und mobiles Detailfenster funktionieren.');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('.is-awaiting').count(),0);
  assert.equal(await page.locator('.motion-toggle').getAttribute('aria-pressed'),'true');
  await page.locator('[data-dialog="study"] summary').click();
  assert.equal(await page.locator('dialog').evaluate(el=>getComputedStyle(el).opacity),'1');
  await page.keyboard.press('Escape');
  checks.push('Reduzierte Bewegung wird respektiert; Dialog bleibt sichtbar.');
  await page.goto('http://127.0.0.1:8080/kontakt-datenschutz.html',{waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await page.getByRole('link',{name:'nico@hoammade.de',exact:true}).count(),1);
  const noJs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const fallback=await noJs.newPage();await fallback.goto('http://127.0.0.1:8080');
  await fallback.locator('[data-dialog="study"] summary').click();
  assert.equal(await fallback.locator('[data-dialog="study"][open]').count(),1);
  assert.equal(await fallback.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  checks.push('Impressum und Inhalte ohne JavaScript bleiben nutzbar.');
  assert.deepEqual(errors,[],'Browser runtime errors.');
  checks.push('Keine JavaScript-Laufzeitfehler.');
  await writeFile('.qa/results/report.json',JSON.stringify({status:'passed',checks},null,2));
  console.log(JSON.stringify({status:'passed',checks},null,2));
}catch(e){
  await page.screenshot({path:'.qa/results/failure.webp',type:'webp',quality:75});
  await writeFile('.qa/results/report.json',JSON.stringify({status:'failed',error:e.stack,checks,errors},null,2));
  console.error(e);process.exitCode=1;
}finally{await browser.close();}
